final class LocaleOption {
  const LocaleOption({required this.locale, required this.nativeName});

  final Locale locale;
  final String nativeName;
}

final class AppTranslations extends Translations {
  AppTranslations();

  static const Locale fallbackLocale = Locale('en');

  static const List<LocaleOption> languageOptions = [
    LocaleOption(locale: Locale('en'), nativeName: 'English'),
    LocaleOption(locale: Locale('fr'), nativeName: 'Français'),
    LocaleOption(locale: Locale('ja'), nativeName: '日本語'),
    LocaleOption(locale: Locale('ko'), nativeName: '한국어'),
    LocaleOption(locale: Locale('de'), nativeName: 'Deutsch'),
    LocaleOption(locale: Locale('es'), nativeName: 'Español'),
    LocaleOption(locale: Locale('it'), nativeName: 'Italiano'),
    LocaleOption(locale: Locale('pt'), nativeName: 'Português'),
    LocaleOption(locale: Locale('ru'), nativeName: 'Русский'),
    LocaleOption(locale: Locale('zh', 'TW'), nativeName: '繁體中文'),
    LocaleOption(locale: Locale('zh', 'CN'), nativeName: '简体中文'),
    LocaleOption(locale: Locale('ar'), nativeName: 'العربية'),
  ];

  static List<Locale> get supportedLocales => languageOptions
      .map((LocaleOption option) {
        return option.locale;
      })
      .toList(growable: false);

  static Locale resolveInitialLocale() {
    final String storedLanguage = LocaleSelected.readLanguage();
    if (storedLanguage.isNotEmpty) {
      return normalizeLocale(storedLanguage);
    }
    return normalizeLocale(PlatformDispatcher.instance.locale.toLanguageTag());
  }

  static Future<void> selectLanguage(Locale locale) async {
    final Locale normalizedLocale = normalizeLocale(locale.toLanguageTag());
    await LocaleSelected.saveLanguage(normalizedLocale.toLanguageTag());
    await Get.updateLocale(normalizedLocale);
    NotificationService.instance.refreshNotificationLanguage();
  }

  static Locale normalizeLocale(String languageTag) {
    final String normalizedTag = languageTag
        .trim()
        .replaceAll('_', '-')
        .toLowerCase();
    final List<String> tagParts = normalizedTag.split('-');
    final String languageCode = tagParts.first;

    if (languageCode == 'zh') {
      final bool useTraditional = tagParts.any(
        (String part) => const {'tw', 'hk', 'mo', 'hant'}.contains(part),
      );
      return Locale('zh', useTraditional ? 'TW' : 'CN');
    }

    const Set<String> supportedCodes = {
      'en',
      'fr',
      'ja',
      'ko',
      'de',
      'es',
      'it',
      'pt',
      'ru',
      'ar',
    };
    return supportedCodes.contains(languageCode)
        ? Locale(languageCode)
        : fallbackLocale;
  }

